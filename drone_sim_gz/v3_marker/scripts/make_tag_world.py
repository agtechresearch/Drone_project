#!/usr/bin/env python3
"""AprilTag markers on the rack posts + a QVIX world turned away from north (v3_marker, 2026-10-29).
  python3 make_tag_world.py [yaw_deg=7.0] [mirror=0]
Writes (all under v3_marker/gz/):
  models/qvix_tags/        static model, one plane per tag (tag36h11, black square 0.04 m, printed 0.05 m incl. white border)
                           on every unit-end post (model y 0.625, 4.575, 4.925, 8.875) of the 8 R1 faces at the two survey
                           heights (0.68, 1.265 m above the floor), facing into the aisle, 1.5 mm in front of the post
  tags_map.json            id -> face, model x/y/z of the tag centre, normal (+1 = +x model / -1), size
  worlds/qvix_rot.sdf      qvix.sdf with the QVIX module (and the tags) turned by yaw_deg about the module origin:
                           the racks no longer run north-south, so "face = 270 deg" cannot be assumed
"""
import json, os, re, sys, shutil
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); V3 = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import qvix_grid as G  # noqa: E402
yaw_deg = float(sys.argv[1]) if len(sys.argv) > 1 else 7.0
mirror = len(sys.argv) > 2 and sys.argv[2] == "1"
TAG_BLACK = 0.04; TAG_PRINT = TAG_BLACK * 10 / 8          # tag36h11 image = 8x8 black-bordered code + 1-cell white border
POSTS_Y = (0.625, 4.575, 4.925, 8.875)
HEIGHTS = (0.68, 1.265)
FACES = [("AE", "A", "E"), ("BW", "B", "W"), ("BE", "B", "E"), ("CW", "C", "W"), ("CE", "C", "E"), ("DW", "D", "W"), ("DE", "D", "E"), ("EW", "E", "W")]
mdir = os.path.join(V3, "gz", "models", "qvix_tags"); tdir = os.path.join(mdir, "materials", "textures")
if os.path.isdir(mdir):
    shutil.rmtree(mdir)
os.makedirs(tdir)
tags = {}; links = ""; tid = 0
for face, col, side in FACES:
    x0, x1 = G.AISLES[col]
    fx = x0 if side == "W" else x1            # rack face plane (model x)
    nrm = 1.0 if side == "W" else -1.0        # into the aisle
    for py in POSTS_Y:
        for hz in HEIGHTS:
            im = Image.open(os.path.join(V3, "gz", "tags", "tag36_11_%05d.png" % tid)).convert("RGB").resize((400, 400), Image.NEAREST)
            if mirror:
                im = im.transpose(Image.FLIP_LEFT_RIGHT)
            fn = "tag_%02d.png" % tid; im.save(os.path.join(tdir, fn))
            # the posts stand 7.5 mm proud of the tray fronts toward the aisle (ray cast of qvix_r_racks.stl, 2026-10-29);
            # the 2 mm tag box sits on the post front
            cx = fx + nrm * (0.0075 + 0.001 + 0.0005)
            tags[tid] = {"face": face, "x": round(cx, 4), "y": py, "z": hz, "normal": nrm, "size": TAG_BLACK}
            yaw = 0.0 if nrm > 0 else 3.14159265
            links += """    <link name="tag_%02d">
      <pose>%.4f %.4f %.4f 0 0 %.6f</pose>
      <visual name="v">
        <geometry><box><size>0.002 %.4f %.4f</size></box></geometry>
        <material><diffuse>1 1 1 1</diffuse><ambient>1 1 1 1</ambient><emissive>0 0 0 1</emissive>
          <pbr><metal><albedo_map>model://qvix_tags/materials/textures/%s</albedo_map><metalness>0</metalness><roughness>1</roughness></metal></pbr>
        </material>
        <cast_shadows>false</cast_shadows>
      </visual>
    </link>
""" % (tid, cx, py, hz, yaw, TAG_PRINT, TAG_PRINT, fn)
            tid += 1
open(os.path.join(mdir, "model.sdf"), "w").write("""<?xml version="1.0"?>
<!-- Generated by v3_marker/scripts/make_tag_world.py: AprilTag tag36h11 markers on the QVIX R1 rack posts (model frame) -->
<sdf version="1.9"><model name="qvix_tags"><static>true</static>
%s</model></sdf>
""" % links)
open(os.path.join(mdir, "model.config"), "w").write("""<?xml version="1.0"?><model><name>qvix_tags</name><version>1.0</version>
<sdf version="1.9">model.sdf</sdf><description>AprilTags on QVIX R1 rack posts (v3_marker)</description></model>
""")
json.dump({"family": "tag36h11", "size_m": TAG_BLACK, "frame": "QVIX model (x east-ish across aisles, y along the aisle, z above the floor)",
           "module_yaw_deg_in_world": yaw_deg, "tags": tags}, open(os.path.join(V3, "gz", "tags_map.json"), "w"), indent=1)
# world: the existing qvix.sdf with the module + tags turned by yaw_deg
src = open(os.path.join(os.path.dirname(V3), "repo_export", "gz", "worlds", "qvix.sdf")).read()
src = src.replace('<world name="qvix">', '<world name="qvix_rot">')
ox, oy, oz = G.MODEL_TO_WORLD_BASE if hasattr(G, "MODEL_TO_WORLD_BASE") else G.MODEL_TO_WORLD
import math
pose = "%.4f %.4f %.4f 0 0 %.6f" % (ox, oy, oz, math.radians(yaw_deg))
src, n = re.subn(r"(<name>qvix_r_module</name>\s*<pose>)[^<]*(</pose>)", r"\g<1>%s\g<2>" % pose, src)
assert n == 1, "QVIX include not found"
src = src.replace("    <light name=\"sunUTC\"", """    <include>
      <uri>model://qvix_tags</uri>
      <name>qvix_tags</name>
      <pose>%s</pose>
    </include>
    <light name="sunUTC\"""" % pose, 1)
os.makedirs(os.path.join(V3, "gz", "worlds"), exist_ok=True)
open(os.path.join(V3, "gz", "worlds", "qvix_rot.sdf"), "w").write(src)
print("tags", tid, "world yaw", yaw_deg, "->", os.path.join(V3, "gz", "worlds", "qvix_rot.sdf"))
